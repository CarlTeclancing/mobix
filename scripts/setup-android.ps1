param(
    [string]$AndroidSdk = '',
    [switch]$Install,
    [switch]$Persist
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$android = Join-Path $root 'native\android'

$candidates = @(
    $AndroidSdk,
    $env:ANDROID_HOME,
    $env:ANDROID_SDK_ROOT,
    (Join-Path $env:LOCALAPPDATA 'Android\Sdk'),
    (Join-Path $env:USERPROFILE 'AppData\Local\Android\Sdk'),
    'C:\Android\Sdk',
    (Join-Path $env:ProgramFiles 'Android\Sdk')
) | Where-Object { $_ -and $_.Trim() } | Select-Object -Unique

$sdk = $null
foreach ($candidate in $candidates) {
    if ((Test-Path (Join-Path $candidate 'platforms')) -or (Test-Path (Join-Path $candidate 'platform-tools'))) {
        $sdk = (Resolve-Path $candidate).Path
        break
    }
}

if (-not $sdk) {
    $checked = ($candidates -join "`n  ")
    throw "Android SDK not found. Install Android Studio or set ANDROID_HOME.`nChecked:`n  $checked"
}

Write-Host "Android SDK: $sdk"
$env:ANDROID_HOME = $sdk
$env:ANDROID_SDK_ROOT = $sdk
if ($Persist) {
    [Environment]::SetEnvironmentVariable('ANDROID_HOME', $sdk, 'User')
    [Environment]::SetEnvironmentVariable('ANDROID_SDK_ROOT', $sdk, 'User')
    Write-Host "Persisted ANDROID_HOME for the current user. Open a new terminal to pick it up."
}

$localProperties = Join-Path $android 'local.properties'
$escaped = $sdk.Replace('\', '\\').Replace(':', '\:')
Set-Content -Path $localProperties -Value "# Generated by scripts/setup-android.ps1. Do not commit.`nsdk.dir=$escaped" -Encoding ASCII
Write-Host "Wrote $localProperties"

$jdk = Get-Command java -ErrorAction SilentlyContinue
if (-not $jdk) {
    Write-Warning 'Java was not found on PATH. Install JDK 17 and set JAVA_HOME before building.'
} else {
    $version = (& java -version 2>&1) -join "`n"
    Write-Host "Java: $($version.Split("`n")[0])"
    if ($version -notmatch '"?(1\.)?(1[7-9]|[2-9][0-9])') {
        Write-Warning 'Mobix requires JDK 17 or newer. Set JAVA_HOME to a JDK 17+ installation.'
    }
}

$sdkManager = @(
    (Join-Path $sdk 'cmdline-tools\latest\bin\sdkmanager.bat'),
    (Join-Path $sdk 'cmdline-tools\bin\sdkmanager.bat'),
    (Join-Path $sdk 'tools\bin\sdkmanager.bat')
) | Where-Object { Test-Path $_ } | Select-Object -First 1

$required = @('platforms\android-35', 'build-tools\35.0.0', 'platform-tools')
$missing = $required | Where-Object { -not (Test-Path (Join-Path $sdk $_)) }
if ($missing) {
    if ($Install -and $sdkManager) {
        Write-Host "Installing missing SDK packages: $($missing -join ', ')"
        & $sdkManager 'platforms;android-35' 'build-tools;35.0.0' 'platform-tools'
        if ($LASTEXITCODE -ne 0) { throw 'sdkmanager failed. Open Android Studio > SDK Manager and install API 35 + Platform-Tools.' }
    } else {
        Write-Warning "Missing SDK packages: $($missing -join ', '). Re-run with -Install or use Android Studio > SDK Manager."
    }
}

Write-Host ''
Write-Host 'Next:'
Write-Host '  npm run verify:native:android'
Write-Host '  npm run verify:android:build'
