import {createHash} from 'node:crypto';
import {chmodSync, existsSync, readFileSync, readdirSync, statSync, writeFileSync} from 'node:fs';
import {homedir} from 'node:os';
import {join, resolve} from 'node:path';
import {spawnSync} from 'node:child_process';

export const GRADLE_VERSION = '8.9';
export const COMPILE_SDK = 35;
export const MIN_JAVA = 17;

export type Platform = NodeJS.Platform;
export type CommandResult = {status: number | null; stdout: string; stderr: string; error?: Error};
export type SdkResolution = {path: string; source: string; candidates: string[]};
export type Artifact = {kind: 'APK' | 'AAB'; variant: string; path: string; bytes: number; sha256: string};
export type GradleRunner = {command: string; kind: 'wrapper' | 'path'; version?: string};

const WINDOWS = process.platform === 'win32';

export function sdkCandidates(projectRoot: string, environment: NodeJS.ProcessEnv = process.env): {path: string; source: string}[] {
    const candidates: {path: string; source: string}[] = [];
    const add = (value: string | undefined, source: string) => {
        if (!value) return;
        const path = resolve(value);
        if (!candidates.some((candidate) => candidate.path === path)) candidates.push({path, source});
    };
    add(environment.ANDROID_HOME, 'ANDROID_HOME');
    add(environment.ANDROID_SDK_ROOT, 'ANDROID_SDK_ROOT');
    const local = join(projectRoot, 'local.properties');
    if (existsSync(local)) {
        for (const line of readFileSync(local, 'utf8').split(/\r?\n/)) {
            const match = /^\s*sdk\.dir\s*=\s*(.+)\s*$/.exec(line);
            if (!match) continue;
            const raw = match[1].replace(/\\:/g, ':').replace(/\\\\/g, '\\');
            add(raw, 'local.properties');
        }
    }
    if (WINDOWS) {
        add(environment.LOCALAPPDATA ? join(environment.LOCALAPPDATA, 'Android', 'Sdk') : undefined, 'LOCALAPPDATA');
        add(join(homedir(), 'AppData', 'Local', 'Android', 'Sdk'), 'user profile');
        add(join(environment.ProgramFiles ?? 'C:\\Program Files', 'Android', 'Sdk'), 'Program Files');
        add('C:\\Android\\Sdk', 'C:\\Android\\Sdk');
    } else if (process.platform === 'darwin') {
        add(join(homedir(), 'Library', 'Android', 'sdk'), 'Android Studio default');
    } else {
        add(join(homedir(), 'Android', 'Sdk'), 'Android Studio default');
        add('/usr/lib/android-sdk', '/usr/lib/android-sdk');
        add('/opt/android-sdk', '/opt/android-sdk');
    }
    return candidates;
}

export function looksLikeSdk(path: string): boolean {
    if (!existsSync(path) || !statSync(path).isDirectory()) return false;
    return ['platform-tools', 'platforms', 'cmdline-tools', 'tools', 'build-tools'].some((entry) => existsSync(join(path, entry)));
}

export function resolveAndroidSdk(projectRoot: string, environment: NodeJS.ProcessEnv = process.env): SdkResolution | null {
    const candidates = sdkCandidates(projectRoot, environment);
    for (const candidate of candidates) {
        if (looksLikeSdk(candidate.path)) return {...candidate, candidates: candidates.map((item) => item.path)};
    }
    return null;
}

export function sdkInventory(sdkPath: string): {platforms: string[]; buildTools: string[]; hasAdb: boolean; hasSdkManager: boolean; hasEmulator: boolean} {
    const entries = (dir: string) => {
        try {
            return readdirSync(join(sdkPath, dir), {withFileTypes: true})
                .filter((entry) => entry.isDirectory())
                .map((entry) => entry.name)
                .sort();
        } catch {
            return [];
        }
    };
    return {
        platforms: entries('platforms'),
        buildTools: entries('build-tools'),
        hasAdb: existsSync(join(sdkPath, 'platform-tools', WINDOWS ? 'adb.exe' : 'adb')),
        hasSdkManager: ['cmdline-tools/latest/bin', 'cmdline-tools/bin', 'tools/bin'].some((dir) =>
            existsSync(join(sdkPath, dir, WINDOWS ? 'sdkmanager.bat' : 'sdkmanager'))),
        hasEmulator: existsSync(join(sdkPath, 'emulator', WINDOWS ? 'emulator.exe' : 'emulator')),
    };
}

export function adbPath(sdkPath: string | null): string {
    if (sdkPath) {
        const candidate = join(sdkPath, 'platform-tools', WINDOWS ? 'adb.exe' : 'adb');
        if (existsSync(candidate)) return candidate;
    }
    return 'adb';
}

export function serializeSdkDir(path: string): string {
    if (!WINDOWS) return path;
    return path.replace(/\\/g, '\\\\').replace(/:/g, '\\:');
}

export function writeLocalProperties(androidDir: string, sdkPath: string): string {
    const file = join(androidDir, 'local.properties');
    const contents = `# Generated by Mobix. Do not commit this file.\nsdk.dir=${serializeSdkDir(sdkPath)}\n`;
    writeFileSync(file, contents);
    return file;
}

export function runCommand(command: string, args: string[], cwd: string, environment: NodeJS.ProcessEnv = process.env): CommandResult {
    const needsShell = WINDOWS && (/\.(bat|cmd)$/i.test(command) || ['npm', 'npx', 'pnpm', 'yarn', 'gradle', 'gradle.bat'].includes(command));
    const result = spawnSync(command, args, {
        cwd,
        encoding: 'utf8',
        env: environment,
        shell: needsShell,
    });
    return {
        status: result.status,
        stdout: result.stdout ?? '',
        stderr: result.stderr ?? '',
        error: result.error,
    };
}

export function gradleOnPath(): {available: boolean; version?: string} {
    const result = runCommand('gradle', ['--version'], process.cwd());
    if (result.error || result.status !== 0) return {available: false};
    const version = /Gradle\s+([0-9][^\s]*)/i.exec(result.stdout + result.stderr)?.[1];
    return {available: true, version};
}

export function findGradleRunner(androidDir: string): GradleRunner | null {
    const script = join(androidDir, WINDOWS ? 'gradlew.bat' : 'gradlew');
    const jar = join(androidDir, 'gradle', 'wrapper', 'gradle-wrapper.jar');
    if (existsSync(script) && existsSync(jar)) {
        if (!WINDOWS) {
            // npm tarballs may not preserve the executable bit; the wrapper is a POSIX sh script.
            try {
                chmodSync(script, 0o755);
            } catch {
                // Read-only filesystems still work when the bit is already present.
            }
        }
        return {command: script, kind: 'wrapper'};
    }
    const path = gradleOnPath();
    if (path.available) return {command: WINDOWS ? 'gradle.bat' : 'gradle', kind: 'path', version: path.version};
    return null;
}

export function javaVersion(): {available: boolean; major?: number; detail?: string} {
    const result = runCommand('java', ['-version'], process.cwd());
    const output = `${result.stdout}${result.stderr}`.trim();
    if (result.error || result.status !== 0) return {available: false, detail: result.error?.message ?? (output || 'java not found')};
    const match = /version\s+"?(\d+)(?:\.(\d+))?/i.exec(output);
    const major = match ? (match[1] === '1' ? Number(match[2]) : Number(match[1])) : undefined;
    return {available: true, major, detail: output.split(/\r?\n/)[0]};
}

export function sha256(file: string): string {
    return createHash('sha256').update(readFileSync(file)).digest('hex');
}

export function collectAndroidArtifacts(androidDir: string, variant: 'debug' | 'release'): Artifact[] {
    const artifacts: Artifact[] = [];
    const collect = (kind: 'APK' | 'AAB', dir: string) => {
        if (!existsSync(dir)) return;
        for (const name of readdirSync(dir).sort()) {
            const extension = kind === 'APK' ? '.apk' : '.aab';
            if (!name.endsWith(extension)) continue;
            const path = join(dir, name);
            if (!statSync(path).isFile()) continue;
            artifacts.push({kind, variant, path, bytes: statSync(path).size, sha256: sha256(path)});
        }
    };
    collect('APK', join(androidDir, 'app', 'build', 'outputs', 'apk', variant));
    collect('AAB', join(androidDir, 'app', 'build', 'outputs', 'bundle', variant));
    return artifacts;
}

export function formatBytes(bytes: number): string {
    if (bytes < 1024) return `${bytes} B`;
    if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KiB`;
    return `${(bytes / (1024 * 1024)).toFixed(2)} MiB`;
}
